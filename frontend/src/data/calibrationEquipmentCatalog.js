// STORAGE HELPERS FOR DYNAMIC USER-ENTERED CUSTOM EQUIPMENT
// =========================================================================

export const getStoredCustomEquipment = () => {
  if (typeof window === "undefined") return [];
  try {
    const raw = localStorage.getItem("arcl_saved_custom_equipment_names");
    if (!raw) return [];
    const parsed = JSON.parse(raw);
    return Array.isArray(parsed) ? parsed : [];
  } catch (e) {
    return [];
  }
};

export const saveCustomEquipmentToStorage = (equipmentList) => {
  if (typeof window === "undefined" || !equipmentList) return [];
  try {
    const itemsToSave = Array.isArray(equipmentList)
      ? equipmentList
      : [equipmentList];
    const existing = getStoredCustomEquipment();
    const existingSet = new Set(
      existing.map((item) =>
        (typeof item === "string" ? item : item?.name || item?.instrument || "")
          .trim()
          .toLowerCase()
      )
    );

    const merged = [...existing];

    itemsToSave.forEach((item) => {
      const name = (typeof item === "string" ? item : item?.name || item?.instrument || "")
        .trim();
      if (name && name.length >= 2 && !existingSet.has(name.toLowerCase())) {
        existingSet.add(name.toLowerCase());
        merged.unshift(
          typeof item === "object"
            ? {
                name,
                category: item.category || "Custom Saved",
                discipline: item.discipline || "Custom Instrument",
                defaultMake: item.make || item.defaultMake || "",
                defaultModel: item.modelNo || item.defaultModel || "",
                defaultRange: item.instrumentRange || item.defaultRange || "",
                savedAt: new Date().toISOString(),
              }
            : {
                name,
                category: "Custom Saved",
                discipline: "Custom Instrument",
                savedAt: new Date().toISOString(),
              }
        );
      }
    });

    // Cap at most recent 500 entries
    const capped = merged.slice(0, 500);
    localStorage.setItem(
      "arcl_saved_custom_equipment_names",
      JSON.stringify(capped)
    );
    return capped;
  } catch (e) {
    console.warn("Could not save custom equipment to localStorage:", e);
    return [];
  }
};

