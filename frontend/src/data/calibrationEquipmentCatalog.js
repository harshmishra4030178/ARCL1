export const buildUnifiedEquipmentSuggestions = ({
  dbRecords = [],
  websiteProducts = [],
  equipmentTypes = [],
  customList = [],
  currentFormInstruments = [],
} = {}) => {
  const seenMap = new Map();

  const addSuggestion = (item, source, sourceLabel, badgeColor) => {
    if (!item) return;
    const name = (
      typeof item === "string"
        ? item
        : item.name || item.instrument || item.instrumentName || item.title || ""
    ).trim();

    if (!name || name.length < 2) return;

    const key = name.toLowerCase();
    if (seenMap.has(key)) {
      const existing = seenMap.get(key);
      if (!existing.defaultMake && (item.make || item.defaultMake)) {
        existing.defaultMake = item.make || item.defaultMake;
      }
      if (!existing.defaultModel && (item.modelNo || item.defaultModel)) {
        existing.defaultModel = item.modelNo || item.defaultModel;
      }
      if (!existing.defaultRange && (item.instrumentRange || item.defaultRange)) {
        existing.defaultRange = item.instrumentRange || item.defaultRange;
      }
      return;
    }

    seenMap.set(key, {
      id: `eq_${key.replace(/[^a-z0-9]/g, "_")}`,
      name,
      category: item.category?.name || item.category || "General Calibration",
      discipline: item.discipline || "",
      defaultMake: item.make || item.defaultMake || "ARCL",
      defaultModel: item.modelNo || item.defaultModel || "",
      defaultRange: item.instrumentRange || item.defaultRange || "",
      defaultCharges: item.defaultCharges || item.calibrationCharges || 0,
      source,
      sourceLabel,
      badgeColor,
    });
  };

  // 1. Highest Priority: Live Current Form Inputs & Recently / Locally Saved Custom Equipments
  const liveFormItems = Array.isArray(currentFormInstruments) ? currentFormInstruments : [];
  liveFormItems.forEach((item) => {
    const instName = (typeof item === "string" ? item : item?.instrument || item?.name || "").trim();
    if (instName && instName.length >= 2) {
      addSuggestion(
        {
          name: instName,
          make: item.make,
          modelNo: item.modelNo,
          instrumentRange: item.instrumentRange,
          category: "Live Entry",
        },
        "recent",
        "⭐ Active / Custom",
        "bg-amber-100 text-amber-800 border-amber-300"
      );
    }
  });

  const stored = getStoredCustomEquipment();
  const allCustom = [...stored, ...(Array.isArray(customList) ? customList : [])];
  allCustom.forEach((item) =>
    addSuggestion(item, "recent", "⭐ Saved in SRF", "bg-amber-100 text-amber-800 border-amber-300")
  );

  // 2. Second Priority: Existing Database Records
  if (Array.isArray(dbRecords)) {
    dbRecords.forEach((r) => {
      if (r?.instrument) {
        addSuggestion(
          {
            name: r.instrument,
            make: r.make,
            modelNo: r.modelNo,
            instrumentRange: r.instrumentRange,
            category: "Client DB Record",
          },
          "db",
          "⚡ DB Record",
          "bg-blue-100 text-blue-800 border-blue-300"
        );
      }
    });
  }

  // 3. Third Priority: Exact Services & Equipment from Customer-Facing /calibration-services Page
  WEBSITE_CALIBRATION_SERVICES_ITEMS.forEach((item) =>
    addSuggestion(
      item,
      "services",
      "🌐 Calibration Services Page",
      "bg-teal-100 text-teal-900 border-teal-300 font-bold"
    )
  );

  // 4. Fourth Priority: Master Calibration Equipment Catalog (NABL Scope & Precision Labs)
  MASTER_CALIBRATION_EQUIPMENT.forEach((item) =>
    addSuggestion(
      item,
      "catalog",
      "🔬 Calibration Scope",
      "bg-emerald-100 text-emerald-800 border-emerald-300"
    )
  );

  // 4. Fourth Priority: Live Website Products Catalog
  if (Array.isArray(websiteProducts)) {
    websiteProducts.forEach((p) => {
      if (p?.name) {
        addSuggestion(
          {
            name: p.name,
            category: p.category?.name || "ARCL Manufacturing",
            defaultMake: "ARCL Instruments",
            defaultModel: p.modelNo || "",
            defaultRange: p.specifications?.Capacity || "",
          },
          "product",
          "📦 ARCL Product",
          "bg-purple-100 text-purple-800 border-purple-300"
        );
      }
    });
  }

  // 5. Fifth Priority: Equipment Types Categories
  if (Array.isArray(equipmentTypes)) {
    equipmentTypes.forEach((et) => {
      if (et?.name) {
        addSuggestion(
          {
            name: et.name,
            category: "Equipment Category",
            defaultMake: "ARCL",
          },
          "category",
          "🏷️ Category",
          "bg-slate-100 text-slate-800 border-slate-300"
        );
      }
    });
  }

  return Array.from(seenMap.values());
};
